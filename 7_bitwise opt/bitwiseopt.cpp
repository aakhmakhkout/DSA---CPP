#include <iostream>
using namespace std;

// bitwise operators (&)
int main() {
    int a = 4, b = 8;

    cout<< (a & b) << endl;
    cout<< (a | b) << endl;
    cout<< (a ^ b) << endl;
    cout<< (a << 1) << endl;
    cout<< (a << 2) << endl;
    cout<< (a >> 1) << endl;
    cout<< (6 & 10) << endl;
    cout<< (6 | 10) << endl;
    cout<< (6 ^ 10) << endl;
    cout<< (10 << 2) << endl;
    cout<< (10 >> 1) << endl;
    


    return 0;
}